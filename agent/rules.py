def _사람(s: str | None) -> str | None:
    s = (s or "").strip()
    return s.removesuffix(" 씨").removesuffix("씨") or None


def _있나(글: str, 목록: list[str]) -> bool:
    return any(w in 글 for w in 목록)


def _뒤서아님(글: str, 목록: list[str]) -> bool:
    """「하면 · 되면」 바로 뒤에 「서」 가 붙은 「~하면서 · ~되면서」(하는 동안)는 세지 않는다 (v1 과 같은 처리)."""
    for w in 목록:
        i = 글.find(w)
        while i >= 0:
            if 글[i + len(w): i + len(w) + 1] != "서":
                return True
            i = 글.find(w, i + 1)
    return False


def _화자(줄: str) -> str:
    return 줄.split(":", 1)[0].strip()


def _말(줄: str) -> str:
    return 줄.split(": ", 1)[-1]


def _날짜(s: str | None) -> date | None:
    try:
        return date.fromisoformat(s) if s else None
    except ValueError:
        return None


def 인용확인(인용: str | None, 근거들: list[str]) -> bool:
    """인용이 근거 줄 어딘가에 글자 그대로 있는가 (공백은 하나로 보고 비교)."""
    q = 줄정리(인용 or "").strip(" 「」\"'")
    return bool(q) and any(q in 줄정리(x) for x in 근거들)


def 마감종류(할일: dict, m: 회의) -> str:
    """날짜 도구로 마감 표현의 종류를 구한다 (정리 노드가 붙인 값이 있으면 그것)."""
    if 할일.get("마감_종류"):
        return 할일["마감_종류"]
    원문 = (할일.get("마감_원문") or "").strip()
    return 날짜계산(원문, m.회의일, m.기준날짜)["종류"] if 원문 else "없음"


def _마감표현근거에(할일: dict) -> bool:
    원문 = 줄정리(할일.get("마감_원문") or "").rstrip("요")
    return bool(원문) and any(원문 in 줄정리(x) for x in 할일.get("근거") or [])


def 다시계산(할일: dict, m: 회의) -> str | None:
    """C12′ — 마감 표현을 코드가 날짜 도구로 다시 계산한 날짜 (날짜로 못 바꾸는 표현이면 None).
    v2 측정에서 LLM 이 다른 할 일의 도구 결과를 가져다 쓴 것(M4-03 「목요일까지」 → 금요일 날짜)을 잡는다."""
    원문 = (할일.get("마감_원문") or "").strip()
    if not 원문:
        return None
    r = 날짜계산(원문, m.회의일, m.기준날짜)
    return r["날짜"] if r["종류"] == "날짜" else None


def 마감고치기(할일: dict, m: 회의) -> dict:
    """코드가 마감을 바로잡는다 (09-28 작성자 「가」 · 정리 노드에서 부름 · LLM 없음).
    조건: 마감 표현이 **이 할 일의 근거 줄에 글자 그대로** 있고, 날짜 도구가 그 표현을 「날짜」로 확정할 때만.
    LLM 이 날짜를 잘못 옮겼거나(M4-03 「목요일까지」 → 금요일 날짜) 비워 두면 도구 값으로 바꾸고, 원래 값은 「마감_LLM」 에 남긴다.
    근거에 없는 표현 · 모호한 표현 · 기준이 필요한 표현(「수업 전날」)은 건드리지 않는다 → C 규칙이 사람에게 보낸다."""
    다시 = 다시계산(할일, m)
    if 다시 is None or not _마감표현근거에(할일) or 할일.get("마감") == 다시:
        return 할일
    return {**할일, "마감_LLM": 할일.get("마감"), "마감": 다시, "마감_고침": True, "마감_직접씀": False}


def 마감불일치(할일: dict, m: 회의) -> bool:
    """마감이 있는데 ① 도구 없이 직접 썼거나 ② 마감 표현을 다시 계산한 날짜와 다르면 참."""
    if not 할일.get("마감"):
        return False
    다시 = 다시계산(할일, m)
    return bool(할일.get("마감_직접씀")) or (다시 is not None and 다시 != 할일["마감"])


def 재확인(할일: dict, m: 회의) -> dict[str, bool]:
    """B4 재확인 세 가지 (2-가). 모두 참이면 급해도 자동 등록."""
    return {
        "도구가 준 날짜": bool(할일.get("마감")) and not 마감불일치(할일, m),
        "마감 표현이 근거에 있음": _마감표현근거에(할일),
        "담당자가 참석자": _사람(할일.get("담당자")) in m.참석자,
    }


def 검수통과(할일: dict) -> tuple[bool, list[str]]:
    """G13 — 검수 결과의 아니오 목록.
    v3 · v1 형식(담당자 · 마감 · 근거 · 확정): 아니오가 하나라도 있으면 불합격 (인용을 요구하지 않음 — 8-7 원인 3).
    v2 형식(인용 칸이 있는 기록): 인용이 근거 줄에 있는 아니오만 인정 (v2 측정 원본을 다시 채점할 때만).
    검수 답이 없으면 안전하게 불합격."""
    검수 = 할일.get("검수")
    if not 검수:
        return True, []
    if 검수.get("답없음"):
        return False, ["검수 답이 없음"]
    if "확정" in 검수:
        인정 = [k for k in 검수질문 if 검수.get(k) is False]
        return not 인정, 인정
    근거들 = 할일.get("근거") or []
    인정 = []
    if 검수.get("담당자") is False and 인용확인(검수.get("담당자_인용"), 근거들):
        인정.append("담당자")
    if 검수.get("마감") is False and (인용확인(검수.get("마감_인용"), 근거들)
                                     or (할일.get("마감") and not _마감표현근거에(할일))):
        인정.append("마감")
    if 검수.get("근거") is False:
        인정.append("근거")
    for k in ["끝난일", "다음기수", "제안만", "조건미충족"]:
        if 검수.get(k) is True and 인용확인(검수.get("상태_인용"), 근거들):
            인정.append(k)
    return not 인정, 인정


def 검사(할일: dict, m: 회의) -> list[str]:
    """걸린 세부 규칙 번호 목록 (없으면 빈 목록 = 자동 등록 대상)."""
    걸림: list[str] = []
    담당 = _사람(할일.get("담당자"))
    근거들 = [줄정리(x) for x in (할일.get("근거") or [])]
    말들 = " ".join(_말(x) for x in 근거들)
    마감원문 = (할일.get("마감_원문") or "").strip() or None
    마감 = _날짜(할일.get("마감"))
    회의일 = date.fromisoformat(m.회의일)
    원문줄 = [줄정리(x) for x in m.줄들]

    # A 담당자 불분명
    if 담당 is None:
        걸림.append("A1")
    elif 담당 not in m.참석자:
        걸림.append("A2")
    if _있나(담당 or "", 여럿표현) or _있나(말들, 여럿표현):
        걸림.append("A3")
    if 담당 and any(부탁말.search(_말(x)) and _화자(x) == 담당 for x in 근거들):
        걸림.append("A4")
    # B 마감 임박 — 재확인이 하나라도 실패할 때만 (2-가)
    if 마감 and 0 <= (마감 - 회의일).days <= 3 and not all(재확인(할일, m).values()):
        걸림.append("B4")
    # C 마감 불확실
    종류 = 마감종류(할일, m)
    if 마감원문 and 마감 is None and 종류 != "모호":
        걸림.append("C5")
    if 마감원문 and 마감 and 종류 == "모호":
        걸림.append("C6")
    if 마감 and 마감 < 회의일:
        걸림.append("C10")
    if 마감불일치(할일, m):   # C12′ — 마감을 그 마감 표현으로 다시 계산해 맞춰 봄 (8-7)
        걸림.append("C12")
    if not 마감원문 and 날짜말.search(말들):
        걸림.append("C13")
    # D 근거 불일치
    if not 근거들 or any(x not in 원문줄 for x in 근거들):
        걸림.append("D7")
    if 담당 and not any(담당 in x for x in 근거들):
        # 2-마: 부탁하는 줄이고 담당자가 그 줄 바로 앞 줄의 화자면 (부탁받은 사람) 걸지 않는다
        부탁받음 = any(부탁말.search(_말(x)) and x in 원문줄 and 원문줄.index(x) > 0
                     and _화자(원문줄[원문줄.index(x) - 1]) == 담당 for x in 근거들)
        if not 부탁받음:
            걸림.append("D8")
    # E 미확정 논의 — 뜻이 분명한 표현만 (9-다)
    if _있나(말들, 미확정표현):
        걸림.append("E9")
    if _뒤서아님(말들, 조건표현):
        걸림.append("E11")
    # F 바깥 연락 — 뽑기가 낸 연락 대상 칸 (②-가)
    if 할일.get("연락대상") == "바깥":
        걸림.append("F12")
    # G 검수 불합격 — 네 질문 중 아니오가 하나라도 (v3)
    if not 검수통과(할일)[0]:
        걸림.append("G13")
    # H 뽑기 누락 의심 — 그래프 ① 이 만든 「할 일 후보」 는 무조건 사람에게
    if 할일.get("후보"):
        걸림.append("H14")
    # I 중복 — 대조가 앞의 할 일과 같다고 본 뒤의 것 (R4-마)
    if 할일.get("중복_앞건"):
        걸림.append("I15")
    return 걸림


def 묶음(규칙번호: str) -> str:
    return 규칙번호[0]
