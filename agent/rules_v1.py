미확정표현 = ["검토해 보자", "검토해보자", "일단", "아직", "보류", "다음에 다시"]
조건표현 = ["되면", "하면", "확정되면"]
바깥표현 = ["고객", "거래처", "외부", "발송", "전화", "메일 보내"]


def _있나(글: str, 목록: list[str]) -> bool:
    return any(w in 글 for w in 목록)


def _조건있나(글: str) -> bool:
    """E11 — 「하면 · 되면」 바로 뒤에 「서」 가 붙은 「~하면서 · ~되면서」(하는 동안)는 조건이 아니므로 세지 않는다.
    (09-28 측정 전 점검에서 찾은 구현 결함: M1 「작업하면서」 · M5 「수업하면서」. 단어 목록은 그대로)"""
    for w in 조건표현:
        i = 글.find(w)
        while i >= 0:
            if 글[i + len(w): i + len(w) + 1] != "서":
                return True
            i = 글.find(w, i + 1)
    return False


def _날짜(s: str | None) -> date | None:
    try:
        return date.fromisoformat(s) if s else None
    except ValueError:
        return None


def 검사(할일: dict, m: 회의) -> list[str]:
    """걸린 세부 규칙 번호 목록 (없으면 빈 목록 = 자동 등록 대상)."""
    걸림: list[str] = []
    담당 = (할일.get("담당자") or "").strip() or None
    근거들 = [줄정리(x) for x in (할일.get("근거") or [])]
    근거글 = " ".join(근거들)
    마감원문 = (할일.get("마감_원문") or "").strip() or None
    마감 = _날짜(할일.get("마감"))
    회의일 = date.fromisoformat(m.회의일)

    # A 담당자 불분명
    if 담당 is None:
        걸림.append("A1")
    elif 담당.removesuffix(" 씨").removesuffix("씨") not in m.참석자:
        걸림.append("A2")
    if _있나(담당 or "", 여럿표현) or _있나(근거글, 여럿표현):
        걸림.append("A3")
    # B 마감 임박
    if 마감 and 0 <= (마감 - 회의일).days <= 3:
        걸림.append("B4")
    # C 마감 불확실
    if 마감원문 and 마감 is None:
        걸림.append("C5")
    if _있나(마감원문 or "", 모호표현) or _있나(근거글, 모호표현):
        걸림.append("C6")
    if 마감 and 마감 < 회의일:
        걸림.append("C10")
    # D 근거 불일치
    원문줄 = {줄정리(x) for x in m.줄들}
    if not 근거들 or any(x not in 원문줄 for x in 근거들):
        걸림.append("D7")
    if 담당 and not any(담당.removesuffix(" 씨").removesuffix("씨") in x for x in 근거들):
        걸림.append("D8")
    # E 미확정 논의
    if _있나(근거글, 미확정표현):
        걸림.append("E9")
    if _조건있나(근거글):
        걸림.append("E11")
    # F 바깥 연락
    if _있나(할일.get("내용") or "", 바깥표현):
        걸림.append("F12")
    # G 검수 불합격 — 검수 단계가 붙인 결과 {"담당자": bool, "마감": bool, "근거": bool, "확정": bool, "이유": str}
    검수 = 할일.get("검수")
    if 검수 and any(검수.get(k) is False for k in 검수질문):
        걸림.append("G13")
    # H 뽑기 누락 의심 — 그래프 ① 이 만든 「할 일 후보」 는 무조건 사람에게 (09-28 M1 시운전 뒤 추가 · 작성자 승인)
    if 할일.get("후보"):
        걸림.append("H14")
    return 걸림


